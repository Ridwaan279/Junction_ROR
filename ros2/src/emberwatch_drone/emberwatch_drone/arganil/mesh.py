class Obj:
    def __init__(self) -> None:
        self.v: list[tuple[float, float, float]] = []
        self.vt: list[tuple[float, float]] = []
        self.f: list[tuple[int, ...]] = []

    def add_v(self, x, y, z) -> int:
        self.v.append((x, y, z))
        return len(self.v)

    def write(self, path: str, uv: bool = False, normals=None, vertex_precision: int = 2) -> None:
        # Per-vertex normals are REQUIRED: DART's ODE trimesh converter reads aiMesh normals and
        # segfaults on meshes without them.
        if not isinstance(vertex_precision, int) or not 0 <= vertex_precision <= 9:
            raise ValueError('vertex_precision must be an integer from 0 to 9')
        V = np.asarray(self.v, dtype=np.float64)
        if normals is None:
            F = np.asarray(self.f, dtype=np.int64) - 1
            fn = np.cross(V[F[:, 1]] - V[F[:, 0]], V[F[:, 2]] - V[F[:, 0]])
            vn = np.zeros_like(V)
            for k in range(3):
                np.add.at(vn, F[:, k], fn)
        else:
            # Shared surface normals keep independently written LOD tiles seamless.
            vn = np.asarray(normals, dtype=np.float64)
            if vn.shape != V.shape or not np.isfinite(vn).all():
                raise ValueError('normals must be a finite Nx3 array matching vertices')
        ln = np.linalg.norm(vn, axis=1, keepdims=True)
        vn = np.where(ln > 1e-12, vn / np.maximum(ln, 1e-12), np.array([0.0, 0.0, 1.0]))
        with open(path, "w") as fh:
            fh.write("# generated by emberwatch_drone.arganil.worldgen\n")
            fh.write("".join(f"v {x:.{vertex_precision}f} {y:.{vertex_precision}f} {z:.{vertex_precision}f}\n" for x, y, z in self.v))
            fh.write("".join(f"vn {a:.4f} {b:.4f} {c:.4f}\n" for a, b, c in vn))
            fh.write("".join(f"vt {u:.5f} {w:.5f}\n" for u, w in self.vt))
            if uv:
                fh.write("".join("f " + " ".join(f"{i}/{i}/{i}" for i in f) + "\n" for f in self.f))
            else:
                fh.write("".join("f " + " ".join(f"{i}//{i}" for i in f) + "\n" for f in self.f))


def ear_clip(poly: list[tuple[float, float]]) -> list[tuple[int, int, int]]:
    """Triangulate a simple CCW polygon (indices). Falls back to a fan if clipping stalls."""
    idx = list(range(len(poly)))
    tris = []

    def cross(a, b, c):
        return (b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0])

    def inside(p, a, b, c):
        return cross(a, b, p) >= 0 and cross(b, c, p) >= 0 and cross(c, a, p) >= 0

    guard = 0
    while len(idx) > 3 and guard < 10000:
        guard += 1
        for k in range(len(idx)):
            i0, i1, i2 = idx[k - 1], idx[k], idx[(k + 1) % len(idx)]
            a, b, c = poly[i0], poly[i1], poly[i2]
            if cross(a, b, c) <= 1e-9:
                continue
            if any(inside(poly[j], a, b, c) for j in idx if j not in (i0, i1, i2)):
                continue
            tris.append((i0, i1, i2))
            idx.pop(k)
            break
        else:
            break
    if len(idx) == 3:
        tris.append(tuple(idx))
    elif len(idx) > 3:
        tris += [(idx[0], idx[i], idx[i + 1]) for i in range(1, len(idx) - 1)]
    return tris


