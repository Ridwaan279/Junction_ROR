# ------------------------------------------------------------------ mesh helpers
class Obj:
    def __init__(self) -> None:
        self.v: list[tuple[float, float, float]] = []
        self.vt: list[tuple[float, float]] = []
        self.f: list[tuple[int, ...]] = []

    def add_v(self, x, y, z) -> int:
        self.v.append((x, y, z))
        return len(self.v)

    def write(self, path: str, uv: bool = False) -> None:
        # Per-vertex normals are REQUIRED: DART's ODE trimesh converter reads aiMesh normals and
        # segfaults on meshes without them.
        V = np.asarray(self.v, dtype=np.float64)
        F = np.asarray(self.f, dtype=np.int64) - 1
        fn = np.cross(V[F[:, 1]] - V[F[:, 0]], V[F[:, 2]] - V[F[:, 0]])
        vn = np.zeros_like(V)
        for k in range(3):
            np.add.at(vn, F[:, k], fn)
        ln = np.linalg.norm(vn, axis=1, keepdims=True)
        vn = np.where(ln > 1e-12, vn / np.maximum(ln, 1e-12), np.array([0.0, 0.0, 1.0]))
        with open(path, "w") as fh:
            fh.write("# generated by emberwatch_drone.arganil.worldgen\n")
            fh.write("".join(f"v {x:.2f} {y:.2f} {z:.2f}\n" for x, y, z in self.v))
            fh.write("".join(f"vn {a:.4f} {b:.4f} {c:.4f}\n" for a, b, c in vn))
            fh.write("".join(f"vt {u:.5f} {w:.5f}\n" for u, w in self.vt))
            if uv:
                fh.write("".join("f " + " ".join(f"{i}/{i}/{i}" for i in f) + "\n" for f in self.f))
            else:
                fh.write("".join("f " + " ".join(f"{i}//{i}" for i in f) + "\n" for f in self.f))


def ear_clip(poly: list[tuple[float, float]]) -> list[tuple[int, int, int]]:
    """Triangulate a simple CCW polygon (indices). Falls back to a fan if clipping stalls."""
    idx = list(range(len(poly)))
    tris = []

    def cross(a, b, c):
        return (b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0])

    def inside(p, a, b, c):
        return cross(a, b, p) >= 0 and cross(b, c, p) >= 0 and cross(c, a, p) >= 0

    guard = 0
    while len(idx) > 3 and guard < 10000:
        guard += 1
        for k in range(len(idx)):
            i0, i1, i2 = idx[k - 1], idx[k], idx[(k + 1) % len(idx)]
            a, b, c = poly[i0], poly[i1], poly[i2]
            if cross(a, b, c) <= 1e-9:
                continue
            if any(inside(poly[j], a, b, c) for j in idx if j not in (i0, i1, i2)):
                continue
            tris.append((i0, i1, i2))
            idx.pop(k)
            break
        else:
            break
    if len(idx) == 3:
        tris.append(tuple(idx))
    elif len(idx) > 3:
        tris += [(idx[0], idx[i], idx[i + 1]) for i in range(1, len(idx) - 1)]
    return tris


# ------------------------------------------------------------------ terrain
def build_terrain(t: Terrain, out: str) -> tuple[np.ndarray, np.ndarray]:
    g = np.arange(-MAP_HALF_M, MAP_HALF_M + 0.1, TERRAIN_STEP_M)
    E, N = np.meshgrid(g, g)  # rows = north
    Z = t.z_map(E, N)
    n = len(g)
    o = Obj()
    for r in range(n):
        for c in range(n):
            o.add_v(E[r, c], N[r, c], Z[r, c])
            o.vt.append(((E[r, c] + MAP_HALF_M) / (2 * MAP_HALF_M), (N[r, c] + MAP_HALF_M) / (2 * MAP_HALF_M)))
    for r in range(n - 1):
        for c in range(n - 1):
            a = r * n + c + 1
            b, cc, d = a + 1, a + n, a + n + 1
            o.f += [(a, b, d), (a, d, cc)]  # CCW seen from +z
    o.write(os.path.join(out, "terrain.obj"), uv=True)
    return g, Z


def satellite_texture(sat, out: str, px: int = 4096) -> None:
    """Terrain texture = Sentinel-2 cloudless 2016 (EOX, CC BY 4.0) resampled into the map frame."""
    g = np.linspace(-MAP_HALF_M, MAP_HALF_M, px)
    rows = []
    for chunk in np.array_split(g[::-1], 16):  # row 0 = north
        E, N = np.meshgrid(g, chunk)
        rows.append(sat.rgb_map(E, N))
    rgb = np.concatenate(rows, 0) / 255.0
    rgb = np.clip(rgb * 1.35, 0, 1) ** 0.85                     # the mosaic is dark: lift exposure
    grey = rgb.mean(-1, keepdims=True)
    rgb = np.clip(grey + (rgb - grey) * 1.15, 0, 1)              # mild saturation
    Image.fromarray((rgb * 255).astype(np.uint8)).save(os.path.join(out, "terrain.jpg"), quality=90)


def paint_texture(t: Terrain, feats, out: str) -> None:
    px = TEX_PX
    s = px / (2 * MAP_HALF_M)

    def P(x, y):
        return ((x + MAP_HALF_M) * s, (MAP_HALF_M - y) * s)  # image row 0 = north

    # base colour by elevation + slope (no landcover data => generic dry Mediterranean hillside)
    g = np.linspace(-MAP_HALF_M, MAP_HALF_M, 512)
    E, N = np.meshgrid(g, g[::-1])
    Z = t.z_map(E, N)
    gy, gx = np.gradient(Z, g[1] - g[0])
    slope = np.clip(np.hypot(gx, gy), 0, 1.2) / 1.2
    hn = np.clip((Z - Z.min()) / max(1.0, np.ptp(Z)), 0, 1)
    base = np.stack([105 + 40 * slope + 20 * hn, 112 + 10 * hn - 10 * slope, 70 + 15 * slope], -1)
    img = Image.fromarray(base.clip(0, 255).astype(np.uint8)).resize((px, px), Image.BILINEAR)
    d = ImageDraw.Draw(img, "RGBA")
    colors = {"forest": (46, 78, 38, 235), "scrub": (96, 104, 58, 220), "grass": (120, 150, 70, 200),
              "farmland": (150, 150, 85, 200), "orchard": (95, 130, 60, 210), "residential": (150, 140, 128, 190),
              "water": (60, 100, 140, 255)}
    for cls in ["farmland", "grass", "orchard", "scrub", "forest", "residential", "water"]:
        for c2, poly in feats.areas:
            if c2 == cls and len(poly) >= 3:
                d.polygon([P(*p) for p in poly], fill=colors[cls])
    for kind, line in feats.lines:
        w = 7 if kind == "river" else 3
        d.line([P(*p) for p in line], fill=(70, 110, 150, 255) if kind == "river" else (85, 82, 78, 255), width=w)
    for b in feats.buildings:
        d.polygon([P(*p) for p in b.poly], fill=(120, 110, 100, 255))
    img.save(os.path.join(out, "terrain.jpg"), quality=90)


# ------------------------------------------------------------------ buildings
def build_buildings(t: Terrain, blds: list[Building], out: str) -> list[dict]:
    """Walls and roofs as separate meshes with unshared vertices (flat shading, no smeared normals)."""
    walls, roofs, recs = Obj(), Obj(), []
    for b in blds:
        poly = b.poly
        if len(poly) < 3:
            continue
        gz = t.z_map(np.array([p[0] for p in poly]), np.array([p[1] for p in poly]))
        base = float(gz.min()) - 1.0                # sink into slope
        top = float(gz.mean()) + b.height_m         # height above mean ground
        m = len(poly)
        for i in range(m):
            (x0, y0), (x1, y1) = poly[i], poly[(i + 1) % m]
            q = [walls.add_v(x0, y0, base), walls.add_v(x1, y1, base), walls.add_v(x1, y1, top), walls.add_v(x0, y0, top)]
            walls.f += [(q[0], q[1], q[2]), (q[0], q[2], q[3])]
        ring = [roofs.add_v(x, y, top) for x, y in poly]
        for a_, bb, c in ear_clip(poly):
            roofs.f.append((ring[a_], ring[bb], ring[c]))
        recs.append({"osm_id": b.osm_id, "poly": [[round(x, 2), round(y, 2)] for x, y in poly],
                     "base_z": round(base, 2), "top_z": round(top, 2), "height_m": b.height_m,
                     "height_basis": b.height_basis})
    walls.write(os.path.join(out, "buildings_walls.obj"))
    roofs.write(os.path.join(out, "buildings_roofs.obj"))
    return recs


# ------------------------------------------------------------------ trees
def _exclusion_mask(feats, blds, res=2.0):
    """Raster (res m) of places trees may NOT go: building footprints +3 m, roads +4 m, water."""
    n = int(2 * MAP_HALF_M / res)
    img = Image.new("L", (n, n), 0)
    d = ImageDraw.Draw(img)

    def P(x, y):
        return ((x + MAP_HALF_M) / res, (MAP_HALF_M - y) / res)

    for b in blds:
        d.polygon([P(*p) for p in b["poly"]], fill=255, outline=255, width=int(3 / res) * 2 + 1)
    for k, line in feats.lines:
        d.line([P(*p) for p in line], fill=255, width=int(8 / res) + 1)
    for c, poly in feats.areas:
        if c == "water":
            d.polygon([P(*p) for p in poly], fill=255)
    return np.asarray(img) > 0, res, n


def place_trees(t: Terrain, feats, blds: list[dict], sat=None) -> list[dict]:
    """Trees where the satellite image shows dark vegetation (if available), else in OSM forest
    polygons / scattered. Positions are REPRESENTATIVE (no individual tree inventory exists),
    except the few OSM natural=tree nodes."""
    rng = np.random.default_rng(TREE_SEED)
    excl, eres, en = _exclusion_mask(feats, blds)

    def free(X, Y):
        c = ((X + MAP_HALF_M) / eres).astype(int)
        r = ((MAP_HALF_M - Y) / eres).astype(int)
        ok = (c >= 0) & (c < en) & (r >= 0) & (r < en) & (np.abs(X) < MAP_HALF_M - 20) & (np.abs(Y) < MAP_HALF_M - 20)
        ok[ok] &= ~excl[r[ok], c[ok]]
        return ok

    trees: list[dict] = []
    for x, y in feats.trees:
        if free(np.array([x]), np.array([y]))[0]:
            trees.append({"x": x, "y": y, "h": 10.0, "r": 2.8, "kind": "broadleaf", "basis": "osm:natural=tree (height estimated)"})
    resid = [MplPath(p) for c, p in feats.areas if c == "residential"]
    if sat is not None:
        # dense near town (flight area), sparse farther out (the imagery carries the far forest)
        for radius, spacing, cap in ((1900.0, 8.5, MAX_TREES), (MAP_HALF_M, 34.0, MAX_TREES + 3500)):
            g = np.arange(-radius, radius, spacing)
            X, Y = np.meshgrid(g, g)
            X = (X + rng.uniform(-spacing * 0.45, spacing * 0.45, X.shape)).ravel()
            Y = (Y + rng.uniform(-spacing * 0.45, spacing * 0.45, Y.shape)).ravel()
            ring = (np.hypot(X, Y) <= radius) if radius < MAP_HALF_M else (np.hypot(X, Y) > 1900.0)
            X, Y = X[ring], Y[ring]
            rgb = sat.rgb_map(X, Y)
            v = rgb.mean(-1)
            exg = 2 * rgb[:, 1] - rgb[:, 0] - rgb[:, 2]
            score = np.clip((56 - v) / 16, 0, 1) * np.clip((exg - 5) / 8, 0, 1)  # dark + green = canopy
            for rp in resid:
                score[rp.contains_points(np.stack([X, Y], 1))] *= 0.25
            keep = (rng.uniform(size=score.shape) < score) & free(X, Y)
            X, Y = X[keep], Y[keep]
            order = rng.permutation(len(X))  # unbiased spatially when the cap is hit
            for x, y in zip(X[order], Y[order]):
                if len(trees) >= cap:
                    break
                u = rng.uniform()
                kind = "pine" if u < 0.5 else "eucalyptus" if u < 0.8 else "broadleaf"
                h = float(rng.uniform(9, 17) if kind != "broadleaf" else rng.uniform(6, 11))
                trees.append({"x": float(x), "y": float(y), "h": round(h, 2),
                              "r": round(h * (0.22 if kind == "pine" else 0.27 if kind == "eucalyptus" else 0.32), 2),
                              "kind": kind, "basis": "representative (satellite vegetation mask)"})
    else:
        veg = [MplPath(p) for c, p in feats.areas if c in ("forest", "scrub", "orchard")]
        while len(trees) < 1800:
            X, Y = rng.uniform(-MAP_HALF_M, MAP_HALF_M, (2, 4000))
            ok = free(X, Y)
            for x, y in zip(X[ok], Y[ok]):
                if len(trees) >= 1800:
                    break
                if any(p.contains_point((x, y)) for p in veg) or rng.uniform() < 0.3:
                    h = float(rng.uniform(6, 14))
                    trees.append({"x": float(x), "y": float(y), "h": h, "r": round(h * 0.28, 2), "kind": "broadleaf",
                                  "basis": "representative (scattered; no satellite)"})
    xs, ys = np.array([tr["x"] for tr in trees]), np.array([tr["y"] for tr in trees])
    zs = t.z_map(xs, ys)
    for tr, z in zip(trees, zs):
        tr["z"] = round(float(z), 2)
        tr["x"], tr["y"] = round(tr["x"], 2), round(tr["y"], 2)
    return trees


_ICO_V = np.array([(-1, 1.618, 0), (1, 1.618, 0), (-1, -1.618, 0), (1, -1.618, 0), (0, -1, 1.618), (0, 1, 1.618),
                   (0, -1, -1.618), (0, 1, -1.618), (1.618, 0, -1), (1.618, 0, 1), (-1.618, 0, -1), (-1.618, 0, 1)], float)
_ICO_V /= np.linalg.norm(_ICO_V, axis=1, keepdims=True)
_ICO_F = [(0, 11, 5), (0, 5, 1), (0, 1, 7), (0, 7, 10), (0, 10, 11), (1, 5, 9), (5, 11, 4), (11, 10, 2), (10, 7, 6),
          (7, 1, 8), (3, 9, 4), (3, 4, 2), (3, 2, 6), (3, 6, 8), (3, 8, 9), (4, 9, 5), (2, 4, 11), (6, 2, 10),
          (8, 6, 7), (9, 8, 1)]


def build_tree_meshes(trees: list[dict], out: str) -> None:
    rng = np.random.default_rng(TREE_SEED + 1)
    trunk, col = Obj(), Obj()
    crowns = {"pine": Obj(), "eucalyptus": Obj(), "broadleaf": Obj()}

    def prism(o, x, y, z0, z1, r0, r1, k):
        ph = rng.uniform(0, 2 * math.pi)
        bot = [o.add_v(x + r0 * math.cos(ph + 2 * math.pi * i / k), y + r0 * math.sin(ph + 2 * math.pi * i / k), z0) for i in range(k)]
        top = [o.add_v(x + r1 * math.cos(ph + 2 * math.pi * i / k), y + r1 * math.sin(ph + 2 * math.pi * i / k), z1) for i in range(k)]
        for i in range(k):
            j = (i + 1) % k
            o.f += [(bot[i], bot[j], top[j]), (bot[i], top[j], top[i])]
        return bot, top

    def cone(o, x, y, z0, z1, r, k=9):
        ph = rng.uniform(0, 2 * math.pi)
        ring = [o.add_v(x + r * rng.uniform(0.85, 1.1) * math.cos(ph + 2 * math.pi * i / k),
                        y + r * rng.uniform(0.85, 1.1) * math.sin(ph + 2 * math.pi * i / k), z0) for i in range(k)]
        tip, base = o.add_v(x, y, z1), o.add_v(x, y, z0 + 0.3)
        for i in range(k):
            j = (i + 1) % k
            o.f += [(ring[i], ring[j], tip), (ring[j], ring[i], base)]

    def blob(o, x, y, z, rx, rz):
        jit = rng.uniform(0.82, 1.15, 12)
        ids = [o.add_v(x + v[0] * rx * jit[i], y + v[1] * rx * jit[i], z + v[2] * rz * jit[i]) for i, v in enumerate(_ICO_V)]
        o.f += [(ids[a], ids[b], ids[c]) for a, b, c in _ICO_F]

    for tr in trees:
        x, y, z, h, r, kind = tr["x"], tr["y"], tr["z"] - 0.4, tr["h"], tr["r"], tr.get("kind", "broadleaf")
        cr = crowns[kind]
        if kind == "pine":   # maritime-pine-like: tall bare trunk, layered conical crown
            prism(trunk, x, y, z, z + h * 0.62, max(0.14, r * 0.10), max(0.08, r * 0.06), 6)
            cone(cr, x, y, z + h * 0.45, z + h * 0.86, r)
            cone(cr, x, y, z + h * 0.66, z + h + 0.4, r * 0.72)
        elif kind == "eucalyptus":  # narrow, tall, two offset blobs
            prism(trunk, x, y, z, z + h * 0.7, max(0.12, r * 0.08), 0.08, 6)
            blob(cr, x + rng.uniform(-0.4, 0.4), y + rng.uniform(-0.4, 0.4), z + h * 0.62, r * 0.85, h * 0.20)
            blob(cr, x + rng.uniform(-0.5, 0.5), y + rng.uniform(-0.5, 0.5), z + h * 0.84, r * 0.65, h * 0.15)
        else:                # broadleaf: short trunk, rounded crown
            prism(trunk, x, y, z, z + h * 0.45, max(0.15, r * 0.11), 0.1, 6)
            blob(cr, x, y, z + h * 0.65, r, h * 0.30)
            blob(cr, x + rng.uniform(-r, r) * 0.4, y + rng.uniform(-r, r) * 0.4, z + h * 0.78, r * 0.7, h * 0.2)
        prism(col, x, y, z, z + h + 0.5, r, r, 6)  # collision: prism enclosing trunk + crown
    trunk.write(os.path.join(out, "trees_trunks.obj"))
    for k, o in crowns.items():
        o.write(os.path.join(out, f"trees_crowns_{k}.obj"))
    col.write(os.path.join(out, "trees_collision.obj"))


# ------------------------------------------------------------------ planner raster
def build_raster(t: Terrain, blds: list[dict], trees: list[dict], out: str, mesh_g=None, mesh_z=None) -> None:
    res = RASTER_RES_M
    g = np.arange(-MAP_HALF_M + res / 2, MAP_HALF_M, res)
    E, N = np.meshgrid(g, g)
    # conservative ground: max of cell centre and 4 corners
    zs = [t.z_map(E + dx, N + dy) for dx, dy in [(0, 0), (-res / 2, -res / 2), (res / 2, -res / 2),
                                                   (-res / 2, res / 2), (res / 2, res / 2)]]
    ground = np.max(zs, axis=0).astype(np.float32)
    top = ground.copy()
    kind = np.zeros(ground.shape, np.uint8)
    n = len(g)

    def cells(x0, y0, x1, y1):
        c0, c1 = int((x0 + MAP_HALF_M) // res), int((x1 + MAP_HALF_M) // res) + 1
        r0, r1 = int((y0 + MAP_HALF_M) // res), int((y1 + MAP_HALF_M) // res) + 1
        return max(0, r0), min(n, r1), max(0, c0), min(n, c1)

    for b in blds:
        p = np.array(b["poly"])
        r0, r1, c0, c1 = cells(*p.min(0) - res, *p.max(0) + res)
        if r0 >= r1 or c0 >= c1:
            continue
        pts = np.stack([E[r0:r1, c0:c1].ravel(), N[r0:r1, c0:c1].ravel()], 1)
        inside = MplPath(p).contains_points(pts, radius=res * 0.75).reshape(r1 - r0, c1 - c0)  # touch => occupied
        sub = top[r0:r1, c0:c1]
        upd = inside & (b["top_z"] > sub)
        sub[upd] = b["top_z"]
        kind[r0:r1, c0:c1][upd] = 1
    for tr in trees:
        r0, r1, c0, c1 = cells(tr["x"] - tr["r"] - res, tr["y"] - tr["r"] - res, tr["x"] + tr["r"] + res, tr["y"] + tr["r"] + res)
        sl = (slice(r0, r1), slice(c0, c1))
        d = np.hypot(E[sl] - tr["x"], N[sl] - tr["y"]) <= tr["r"] + res * 0.71
        tz = tr["z"] + tr["h"] + 0.5
        upd = d & (tz > top[sl])
        top[sl][upd] = tz
        kind[sl][upd] = 2
    np.savez_compressed(os.path.join(out, "obstacles.npz"), res=res, x0=g[0], y0=g[0], ground=ground, top=top, kind=kind,
                        mesh_g=mesh_g, mesh_z=mesh_z.astype(np.float32))  # exact terrain-mesh grid (spawn heights)


