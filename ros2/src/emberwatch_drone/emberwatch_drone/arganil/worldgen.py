def mesh_model(name, out, visuals, collisions):
    vis = "".join(f'<visual name="{v[0]}"><geometry><mesh><uri>{os.path.join(out, v[1])}</uri></mesh></geometry>{v[2]}</visual>'
                  for v in visuals)
    col = "".join(f'<collision name="{c[0]}"><geometry><mesh><uri>{os.path.join(out, c[1])}</uri></mesh></geometry></collision>'
                  for c in collisions)
    return f'<model name="{name}"><static>true</static><link name="link">{vis}{col}</link></model>'


def mat(rgb, tex=None, rough=0.9):
    r, g, b = rgb
    pbr = f"<pbr><metal><albedo_map>{tex}</albedo_map><roughness>{rough}</roughness><metalness>0</metalness></metal></pbr>" if tex else ""
    return (f"<material><ambient>{r} {g} {b} 1</ambient><diffuse>{r} {g} {b} 1</diffuse>"
            f"<specular>0.05 0.05 0.05 1</specular>{pbr}</material>")


def write_world(out: str, origin_elev: float) -> None:
    pl = "\n".join(f'    <plugin filename="gz-sim-{p}"/>' for p in PX4_SYSTEMS)
    models = [
        mesh_model("arganil_terrain", out, [("v", "terrain.obj", mat((1, 1, 1), os.path.join(out, "terrain.jpg")))],
                   [("c", "terrain.obj")]),
        mesh_model("arganil_buildings", out, [("walls", "buildings_walls.obj", mat((0.90, 0.87, 0.80))),
                                              ("roofs", "buildings_roofs.obj", mat((0.66, 0.30, 0.20)))],
                   [("walls_c", "buildings_walls.obj"), ("roofs_c", "buildings_roofs.obj")]),
        mesh_model("arganil_trees", out, [("trunks", "trees_trunks.obj", mat((0.30, 0.21, 0.13))),
                                          ("pine", "trees_crowns_pine.obj", mat((0.10, 0.21, 0.09))),
                                          ("eucalyptus", "trees_crowns_eucalyptus.obj", mat((0.20, 0.30, 0.19))),
                                          ("broadleaf", "trees_crowns_broadleaf.obj", mat((0.19, 0.33, 0.11)))],
                   [("c", "trees_collision.obj")]),
    ]
    sdf = f"""<?xml version="1.0"?>
<!-- GENERATED by emberwatch_drone.arganil.worldgen - Arganil (PT) demo world. Terrain: Mapterhorn
     (DGT LiDAR DEM CC BY 4.0 / Copernicus GLO-30). Buildings/trees/landuse: (c) OpenStreetMap
     contributors, ODbL. Many trees and all unknown building heights are REPRESENTATIVE estimates.
     World frame: ENU metres about map origin {MAP_ORIGIN}; z = elevation - {origin_elev:.1f} m.
     spherical_coordinates is overwritten by PX4 from PX4_HOME_LAT/LON/ALT (same origin). -->
<sdf version="1.9">
  <world name="emberwatch_arganil">
    <physics type="ode"><max_step_size>0.004</max_step_size><real_time_factor>1.0</real_time_factor>
      <real_time_update_rate>250</real_time_update_rate></physics>
{pl}
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors"><render_engine>ogre2</render_engine></plugin>
    <gravity>0 0 -9.8</gravity>
    <magnetic_field>6e-06 2.3e-05 -4.2e-05</magnetic_field>
    <atmosphere type="adiabatic"/>
    <scene><grid>false</grid><ambient>0.55 0.55 0.58 1</ambient><background>0.62 0.72 0.85 1</background>
      <shadows>true</shadows><sky></sky></scene>
    <light name="sun" type="directional"><pose>0 0 1000 0 0 0</pose><cast_shadows>true</cast_shadows>
      <intensity>1.1</intensity><direction>-0.45 0.35 -0.82</direction><diffuse>1 0.95 0.86 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular><attenuation><range>20000</range><constant>1</constant><linear>0</linear><quadratic>0</quadratic></attenuation></light>
    {chr(10).join(models)}
    <spherical_coordinates><surface_model>EARTH_WGS84</surface_model><world_frame_orientation>ENU</world_frame_orientation>
      <latitude_deg>{MAP_ORIGIN[0]}</latitude_deg><longitude_deg>{MAP_ORIGIN[1]}</longitude_deg><elevation>{origin_elev:.2f}</elevation></spherical_coordinates>
  </world>
</sdf>
"""
    open(os.path.join(out, "emberwatch_arganil.sdf"), "w").write(sdf)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data", default=os.path.expanduser("~/px4/geodata"))
    ap.add_argument("--out", required=True)
    ap.add_argument("--no-satellite", action="store_true", help="fallback: OSM-painted texture, scattered trees")
    a = ap.parse_args(argv)
    out = os.path.abspath(a.out)
    os.makedirs(out, exist_ok=True)
    t = Terrain(os.path.join(a.data, "tiles"))
    feats = load_osm(os.path.join(a.data, "osm_arganil.json"))
    sat = None
    if os.path.isdir(os.path.join(a.data, "s2")) and not a.no_satellite:
        sat = Satellite(os.path.join(a.data, "s2"))
    tg, tZ = build_terrain(t, out)
    if sat is not None:
        satellite_texture(sat, out)
    else:  # simpler fallback: painted from OSM landuse
        paint_texture(t, feats, out)
    blds = build_buildings(t, feats.buildings, out)
    trees = place_trees(t, feats, blds, sat)
    build_tree_meshes(trees, out)
    build_raster(t, blds, trees, out, tg, tZ)
    write_world(out, t.origin_elev)
    meta = {
        "map_origin_lat_lon": MAP_ORIGIN, "map_half_m": MAP_HALF_M, "origin_elevation_m": round(t.origin_elev, 2),
        "terrain": {"source": "Mapterhorn terrain tiles (Terrarium, z%d)" % t.z, "url": "https://tiles.mapterhorn.com/",
                    "underlying": "DGT LiDAR DEM of mainland Portugal (CC BY 4.0) / Copernicus GLO-30 per Mapterhorn attribution.json",
                    "mesh_step_m": TERRAIN_STEP_M},
        "osm": {"license": "ODbL 1.0", "attribution": "(c) OpenStreetMap contributors", "osm_base": feats.osm_base},
        "approximations": {
            "building_height": f"osm height if present; else building:levels*{DEFAULT_LEVEL_H_M}+1 m; else {DEFAULT_BUILDING_H_M} m estimate",
            "building_base": "min terrain under footprint - 1 m; top = mean terrain + height; flat roofs",
            "trees": "OSM natural=tree nodes (height estimated) + REPRESENTATIVE trees placed where the Sentinel-2 image "
                     f"shows dark-green canopy (seed {TREE_SEED}); species mix/heights/positions are not surveyed",
            "terrain_texture": "Sentinel-2 cloudless 2016 by EOX (CC BY 4.0), brightened; fallback painted from OSM",
            "satellite": {"source": "EOxCloudless https://cloudless.eox.at by EOX IT Services GmbH (Contains modified "
                                    "Copernicus Sentinel data 2016)", "license": "CC BY 4.0", "layer": "s2cloudless_3857",
                          "used": sat is not None},
            "osm_completeness": "OSM building coverage around Arganil is incomplete; missing buildings are not modelled"},
        "counts": {"buildings": len(blds), "trees": len(trees),
                   "trees_mapped": sum(1 for tr in trees if tr["basis"].startswith("osm")),
                   "building_height_basis": {k: sum(1 for b in blds if b["height_basis"] == k)
                                             for k in {b["height_basis"] for b in blds}}},
        "buildings": blds, "trees": trees,
    }
    json.dump(meta, open(os.path.join(out, "features.json"), "w"))
    print(json.dumps({k: meta[k] for k in ("origin_elevation_m", "counts")}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
